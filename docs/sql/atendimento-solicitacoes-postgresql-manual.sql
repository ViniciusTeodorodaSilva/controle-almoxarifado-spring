CREATE TABLE necessidade_compra (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_solicitacao_id INT NOT NULL,
 solicitacao_id INT NOT NULL,
 produto_id INT NOT NULL,
 almoxarifado_id INT NOT NULL,
 responsavel_id INT NOT NULL,
 quantidade DOUBLE PRECISION NOT NULL,
 status VARCHAR(30) NOT NULL,
 data_hora TIMESTAMP(6) NOT NULL,
 motivo VARCHAR(100) NOT NULL,
 chave_idempotencia VARCHAR(100) COLLATE "C" NOT NULL,
 assinatura_payload VARCHAR(64) NOT NULL,
 CONSTRAINT uk_necessidade_item UNIQUE (item_solicitacao_id),
 CONSTRAINT uk_necessidade_chave UNIQUE (chave_idempotencia),
 CONSTRAINT fk_necessidade_item FOREIGN KEY (item_solicitacao_id) REFERENCES item_solicitacao(id),
 CONSTRAINT fk_necessidade_solic FOREIGN KEY (solicitacao_id) REFERENCES solicitacao(id),
 CONSTRAINT fk_necessidade_prod FOREIGN KEY (produto_id) REFERENCES produto(id),
 CONSTRAINT fk_necessidade_local FOREIGN KEY (almoxarifado_id) REFERENCES almoxarifado(id),
 CONSTRAINT fk_necessidade_resp FOREIGN KEY (responsavel_id) REFERENCES funcionario(id),
 CONSTRAINT ck_necessidade_quantidade CHECK (quantidade > 0),
 CONSTRAINT ck_necessidade_status CHECK (status IN ('ABERTA','ATENDIDA','CANCELADA'))
);
CREATE INDEX ix_necessidade_solic ON necessidade_compra(solicitacao_id);
CREATE INDEX ix_necessidade_filtros ON necessidade_compra(status, produto_id, almoxarifado_id);
