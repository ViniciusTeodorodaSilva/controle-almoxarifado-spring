CREATE TABLE atendimento_solicitacao (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 solicitacao_id INT NOT NULL,
 responsavel_id INT NOT NULL,
 data_hora TIMESTAMP(6) NOT NULL,
 chave_idempotencia VARCHAR(100) COLLATE "C" NOT NULL,
 assinatura_payload VARCHAR(64) NOT NULL,
 CONSTRAINT uk_atendimento_chave UNIQUE (chave_idempotencia),
 CONSTRAINT fk_atendimento_solic FOREIGN KEY (solicitacao_id) REFERENCES solicitacao(id),
 CONSTRAINT fk_atendimento_resp FOREIGN KEY (responsavel_id) REFERENCES funcionario(id)
);
CREATE INDEX ix_atendimento_solic ON atendimento_solicitacao(solicitacao_id);

CREATE TABLE item_atendimento_solicitacao (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 atendimento_id INT NOT NULL,
 item_solicitacao_id INT NOT NULL,
 quantidade DOUBLE PRECISION NOT NULL,
 CONSTRAINT uk_atendimento_item UNIQUE (atendimento_id, item_solicitacao_id),
 CONSTRAINT fk_item_atendimento FOREIGN KEY (atendimento_id) REFERENCES atendimento_solicitacao(id),
 CONSTRAINT fk_item_atendido_solic FOREIGN KEY (item_solicitacao_id) REFERENCES item_solicitacao(id),
 CONSTRAINT ck_item_atendido_quantidade CHECK (quantidade > 0)
);
ALTER TABLE movimentacao ADD COLUMN atendimento_id INT NULL;
